    private static let coveredColumns = "id, file_path, bookmark, detector_ids, categories, is_screenshot, covered, caught_at, updated_at, tags_written"

    public func coveredFiles() throws -> [CoveredFileRecord] {
        try db.query("SELECT \(Self.coveredColumns) FROM covered_files ORDER BY caught_at, id", [], Self.covered(from:))
    }

    public func coveredFile(_ id: UUID) throws -> CoveredFileRecord? {
        try db.first("SELECT \(Self.coveredColumns) FROM covered_files WHERE id = ?", [.text(id.uuidString)], Self.covered(from:))
    }

    @discardableResult
    public func upsertCoveredFile(_ record: CoveredFileRecord) throws -> [UUID] {
        var displaced: [UUID] = []
        try db.transaction {
            displaced = try db.query("SELECT id FROM covered_files WHERE file_path = ? AND id <> ?",
                                     [.text(record.filePath), .text(record.id.uuidString)]) { r in
                guard let id = UUID(uuidString: r.string(0)) else { throw JournalError.corruptRecord("covered file id \(r.string(0))") }
                return id
            }
            try db.run("DELETE FROM covered_files WHERE file_path = ? AND id <> ?", [.text(record.filePath), .text(record.id.uuidString)])
            try db.run("""
                INSERT INTO covered_files (\(Self.coveredColumns)) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(id) DO UPDATE SET file_path = excluded.file_path, bookmark = excluded.bookmark,
                  detector_ids = excluded.detector_ids, categories = excluded.categories, is_screenshot = excluded.is_screenshot,
                  covered = excluded.covered, caught_at = excluded.caught_at, updated_at = excluded.updated_at,
                  tags_written = excluded.tags_written
                """, [.text(record.id.uuidString), .text(record.filePath), record.bookmark.map { .blob($0) } ?? .null,
                      .text(try JSON.strings(record.detectorIDs)), .text(try JSON.strings(record.categories)), SQLValue(record.isScreenshot),
                      SQLValue(record.covered), .text(ISO.string(record.caughtAt)), .text(ISO.string(record.updatedAt)),
                      .text(try JSON.strings(record.tagsWritten))])
        }
        return displaced
    }

