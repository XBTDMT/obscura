    // MARK: - Import / export

    /// The rules document, with each readable rule's value in plain text: an export is the person's own explicit act,
    /// to a file they choose, and it is how rules move to another Mac, which cannot open this Mac's sealed values
    /// (G-30). A rule whose value cannot be read here has nothing to export and is left out (counted in the log).
    public func exportRules() throws -> Data {
        let stored = try rules()
        let readable = stored.compactMap(\.readable)
        if readable.count < stored.count { Log.journal.error("rules export left out unreadable=\(stored.count - readable.count)") }
        let document = RulesDocument(exportedAt: clock.now(), rules: readable, detectorOverrides: try overrides(),
                                     detectorState: try detectorState(), defaultStyle: try defaultStyle())
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        encoder.dateEncodingStrategy = .iso8601
        return try encoder.encode(document)
    }

    public func importRules(_ data: Data, conflicts policy: ImportConflictPolicy) throws -> ImportReport {
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        let decoded: RulesDocument
        do { decoded = try decoder.decode(RulesDocument.self, from: data) } catch { throw JournalError.invalidImport(String(describing: error)) }
        guard decoded.formatVersion <= RulesDocument.currentFormat else {
            throw JournalError.invalidImport("format \(decoded.formatVersion) is newer than \(RulesDocument.currentFormat)")
        }
        // Security scan F16/F22: the file is untrusted; every field is checked before anything is stored.
        let (document, rejected) = RulesImportValidation.validate(decoded)
        var report = ImportReport(policy: policy)
        report.rejected = rejected
        if !rejected.isEmpty { Log.journal.notice("rules import refused items=\(rejected.count)") }
        // A sealing migration that waits is tried here, never from inside the transaction below.
        try ensureSealed()
        let incomingWins = policy == .preferIncoming
        // Sealing needs the latest schema and this store's key; both are settled before the transaction, so nothing
        // half-imports.
        if !document.rules.isEmpty || !document.detectorOverrides.isEmpty {
            guard try ensureSealed() else { throw JournalError.ruleKeyUnavailable }
            try prepareSealing()
        }
        try db.transaction {
            // F22: keyed by canonical id and merged, never trapped on; a row stored under another spelling keeps its id.
            let existingRules = Dictionary(try (schemaVersion >= Self.sealedRulesVersion ? loadRules() : []).map { (RulesImportValidation.canonicalRuleID($0.id) ?? $0.id, $0) },
                                           uniquingKeysWith: { first, _ in first })
            for incoming in document.rules {
                var rule = incoming
                if let stored = existingRules[incoming.id] { rule.id = stored.id }
                switch existingRules[incoming.id] {
                case .readable(let existing):
                    if existing == rule { report.rulesUnchanged.append(rule.id); continue }
                    report.conflicts.append(.rule(id: rule.id, existing: existing, incoming: rule))
                    if incomingWins { try writeRule(rule) }
                case .unreadable:
                    // G-30: the stored value cannot be read on this Mac, so there is nothing to keep: the file's value
                    // restores the rule whatever the policy (this is how rules come back after a restore elsewhere).
                    try writeRule(rule); report.rulesRecovered.append(rule.id)
                case nil:
                    try writeRule(rule); report.rulesAdded.append(rule.id)
                }
            }
            let existingOverrides = Dictionary(try storedOverrides(migrating: false).readable.map { ($0.detectorID, $0) }, uniquingKeysWith: { first, _ in first })
            for override in document.detectorOverrides {
                guard (try? JSONSerialization.jsonObject(with: Data(override.specsJSON.utf8))) is [Any] else {
                    throw JournalError.corruptRecord("override for \(override.detectorID) is not a JSON array")
                }
                if let existing = existingOverrides[override.detectorID] {
                    if existing.specsJSON == override.specsJSON { report.overridesUnchanged.append(override.detectorID); continue }
                    report.conflicts.append(.override(detectorID: override.detectorID, existing: existing, incoming: override))
                    if incomingWins { try writeOverride(override.detectorID, specsJSON: override.specsJSON) }
                } else {
                    // New here, or stored but unreadable on this Mac (F15): the file's list is the one to use.
                    try writeOverride(override.detectorID, specsJSON: override.specsJSON); report.overridesAdded.append(override.detectorID)
                }
            }
            let existingState = try detectorState()
            for (id, enabled) in document.detectorState.sorted(by: { $0.key < $1.key }) {
                if let existing = existingState[id] {
                    if existing == enabled { report.statesUnchanged.append(id); continue }
                    report.conflicts.append(.detectorState(detectorID: id, existing: existing, incoming: enabled))
                    if incomingWins { try setDetectorEnabled(id, enabled: enabled) }
                } else {
                    try setDetectorEnabled(id, enabled: enabled); report.statesAdded.append(id)
                }
            }
            let current = try defaultStyle()
            if !current.sameAppearance(as: document.defaultStyle) {
                report.conflicts.append(.defaultStyle(existing: current, incoming: document.defaultStyle))
                if incomingWins { try setDefaultStyle(document.defaultStyle); report.defaultStyleChanged = true }
            }
        }
        return report
    }
}

