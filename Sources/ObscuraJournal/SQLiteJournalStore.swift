    /// Every edited detector, its sealed pattern list opened with its key, or the reason it could not be (F15). While
    /// schema 9 waits for the key store, the plain lists are not read at all: every one reads as `keyUnavailable`.
    private func storedOverrides(migrating: Bool = true) throws -> (readable: [OverrideRecord], unreadable: [UnreadableOverride]) {
        guard (migrating ? try ensureSealed() : false) || schemaVersion >= Self.sealedOverridesVersion else {
            let waiting = try db.query("SELECT detector_id, updated_at FROM detector_overrides ORDER BY detector_id", []) { r in
                UnreadableOverride(detectorID: r.string(0), updatedAt: try ISO.date(r.string(1)), problem: .keyUnavailable)
            }
            if !waiting.isEmpty { Log.journal.error("detector overrides unreadable count=\(waiting.count) reason=keyUnavailable") }
            return ([], waiting)
        }
        let rows = try db.query("SELECT detector_id, sealed_specs, updated_at FROM detector_overrides ORDER BY detector_id", []) { r in
            (id: r.string(0), sealed: r.isNull(1) ? Data() : r.data(1), updatedAt: try ISO.date(r.string(2)))
        }
        var readable: [OverrideRecord] = []
        var unreadable: [UnreadableOverride] = []
        for row in rows {
            switch OverrideSeal.open(row.sealed, detectorID: row.id, keys: { openingKey($0) }) {
            case .success(let json): readable.append(OverrideRecord(detectorID: row.id, specsJSON: json, updatedAt: row.updatedAt))
            case .failure(let problem): unreadable.append(UnreadableOverride(detectorID: row.id, updatedAt: row.updatedAt, problem: problem))
            }
        }
        if !unreadable.isEmpty {
            let ids = unreadable.map { "\($0.detectorID):\($0.problem.rawValue)" }.joined(separator: ",")
            Log.journal.error("detector overrides unreadable count=\(unreadable.count) of=\(rows.count) ids=\(ids, privacy: .public)")
        }
        return (readable, unreadable)
    }

