import CryptoKit
public import Foundation
public import ObscuraSupport

/// The Journal on disk: `<root>/obscura.sqlite` (0600, WAL) plus `<root>/Journal.noindex/<UUID>/{original,clean}.<ext>`
/// (0700/0600) and `<root>/Journal.noindex/.trash/<UUID>/` for soft-deleted entries. One connection, owned by this actor.
///
/// G-23: the images folder ends in `.noindex` (Spotlight never indexes it) and is excluded from Time Machine at every
/// launch; `obscura.sqlite` stays backed up (rules, settings, rects and detector ids: the person's work, no image, no
/// recognized text). A Journal from before G-23 (`<root>/Journal`, no suffix) is moved once by `JournalLayoutMigration`.
///
/// G-30: each custom rule's value is sealed (AES-GCM, `RuleSeal`) with a per-install key from `ruleKeys`; no plain rule
/// value is ever written to the file. The key is asked for only when a rule is read or written, and cached.
public actor SQLiteJournalStore: JournalStore {
    public static let databaseName = "obscura.sqlite"
    public static let journalFolderName = JournalLocations.imagesFolderName
    public static let trashFolderName = ".trash"
    public static let statsRetentionDays = 90

    public nonisolated let root: URL
    /// The images folder (`Journal.noindex`): never indexed, never backed up.
    public nonisolated let journalRoot: URL
    /// `Obscura-Backups/` beside the root: where the layout migration keeps its copy. Excluded from backup.
    public nonisolated let backupsRoot: URL
    /// What the layout migration did at this launch.
    nonisolated let layoutMigration: JournalLayoutMigration.Report
    nonisolated let databaseURL: URL
    /// The pre-G-23 images folder. Read only while a stopped migration left entries in it, so they stay readable.
    nonisolated let legacyJournalRoot: URL
    private let clock: any WallClock
    private let db: SQLiteConnection
    private let fm = FileManager.default
    /// Where the rule keys live (G-30): the Keychain in the app and the CLI, memory in tests.
    private let ruleKeys: any RuleKeyStore
    /// F21 (G-34): the only key this store seals with, generated by this store itself and stored under its id. A key the
    /// key store already held is never sealed with, whoever put it there. Never logged, never written anywhere else.
    private var sessionKey: SymmetricKey?
    /// Keys the key store handed over to open values, by id, once their bytes were checked against that id.
    private var openedKeys: [Data: SymmetricKey] = [:]
    /// The schema the file is at. Below 8 (or 9) while a sealing migration waits for the key store (it did not answer
    /// when plain values needed sealing): the old rows stay as they were and read as `keyUnavailable` until a later read
    /// or write seals them.
    private var schemaVersion: Int

    /// Where a test stops `commitRender` (G-28): after the new clean file is written, before the rows change; with
    /// `afterFileWriteAndRestore`, putting the previous file back fails too.
    enum CommitFault: Sendable { case afterFileWrite, afterFileWriteAndRestore }
    private var commitFault: CommitFault?
    /// Where a test stops a table-rebuilding migration's step (G-40's schema 10), at open and at every later try.
    private let schemaFault: SchemaMigrationBackup.Fault?
    func setCommitFault(_ fault: CommitFault?) { commitFault = fault }

    /// Opens or creates the store. Throws `JournalError.newerSchema` when the file was written by a newer Obscura.
    /// Moves a pre-G-23 Journal into `Journal.noindex` (with a backup in `backupsRoot`, default `Obscura-Backups` beside
    /// the root), marks the images folder excluded from backup, and purges the trash, as every launch does.
    /// `ruleKeys` holds the key that seals rule values (G-30). It has no default, so every caller says which one: the
    /// Keychain for the real Journal, `InMemoryRuleKeyStore` for a temporary one or a test.
    public init(root: URL, ruleKeys: any RuleKeyStore, clock: any WallClock = SystemClock(), backupsRoot: URL? = nil) throws {
        try self.init(root: root, ruleKeys: ruleKeys, clock: clock, backupsRoot: backupsRoot, layoutFault: nil)
    }

    /// `layoutFault` lets a test stop the layout migration at a chosen step.
    /// `schemaFault` stops a table-rebuilding migration's step (G-40's schema 10) after its backup or after it committed.
    init(root: URL, ruleKeys: any RuleKeyStore, clock: any WallClock, backupsRoot: URL?, layoutFault: JournalLayoutMigration.Fault?,
         schemaFault: SchemaMigrationBackup.Fault? = nil) throws {
        self.root = root
        self.clock = clock
        self.ruleKeys = ruleKeys
        journalRoot = JournalLocations.images(in: root)
        legacyJournalRoot = JournalLocations.legacyImages(in: root)
        self.backupsRoot = backupsRoot ?? JournalLocations.backups(besides: root)
        databaseURL = root.appendingPathComponent(Self.databaseName)
        // F2: no folder the store writes into or deletes from is ever reached through a symbolic link.
        try Self.checkFolders(root: root, images: journalRoot, legacy: legacyJournalRoot, backups: self.backupsRoot)
        try FileAtomics.makePrivateDirectory(root)
        db = try SQLiteConnection(path: databaseURL.path)
        try Self.restrictDatabaseFiles(at: databaseURL)
        let migrated = try Self.migrate(db, now: clock.now(), ruleKeys: ruleKeys, backupsRoot: self.backupsRoot, schemaFault: schemaFault)
        schemaVersion = migrated.version
        sessionKey = migrated.key
        if let key = migrated.key { openedKeys[RuleSeal.keyID(key)] = key }
        self.schemaFault = schemaFault
        layoutMigration = JournalLayoutMigration(root: root, backupsRoot: self.backupsRoot, now: clock.now(), fault: layoutFault).run(db: db)
        try FileAtomics.makePrivateDirectory(journalRoot)
        try Self.keepOutOfBackups(images: journalRoot, backups: self.backupsRoot)
        try Self.ensureDefaultStyle(db)
        // A trash folder that will not go never stops the Journal from opening: it keeps its row and the next prune tries
        // again and reports it (#11).
        _ = try Self.purgeTrash(db, root: root,
                                trashRoots: [journalRoot, legacyJournalRoot].map { $0.appendingPathComponent(Self.trashFolderName, isDirectory: true) })
    }

    /// F2: the root's own last component, the images folders and their trash folders are real folders inside the root
    /// (or not there yet), and the backups folder beside it is not a link. Anything else refuses to open the Journal.
    private static func checkFolders(root: URL, images: URL, legacy: URL, backups: URL) throws {
        try JournalPathSafety.checkRoot(root)
        for (folder, what) in [(images, "images folder"), (legacy, "old images folder")] {
            try JournalPathSafety.checkContained(folder, in: root, what: what)
            try JournalPathSafety.checkContained(folder.appendingPathComponent(trashFolderName, isDirectory: true), in: root, what: "trash folder")
        }
        try JournalPathSafety.checkNotLink(backups, what: "backups folder")
        for suffix in ["", "-wal", "-shm"] where JournalPathSafety.kind(root.appendingPathComponent(databaseName + suffix)) == .symbolicLink {
            throw JournalError.unsafeLocation("database")
        }
    }

    /// Re-applied at every launch: cheap, and a restore or a copy by another tool can drop the attribute.
    private static func keepOutOfBackups(images: URL, backups: URL) throws {
        try BackupExclusion.exclude(images)
        guard FileManager.default.fileExists(atPath: backups.path) else { return }
        try BackupExclusion.exclude(backups)
        for backup in JournalLayoutMigration.allBackups(in: backups) + SchemaMigrationBackup.all(in: backups) {
            // A copy still being written can be renamed between the listing and here (it is excluded when it is made).
            do { try BackupExclusion.exclude(backup) } catch where !FileManager.default.fileExists(atPath: backup.path) { continue }
        }
    }

    // MARK: - Schema

    /// Applies every migration this file is missing. Schema 8 (G-30) seals the plain rule values and schema 9 (F15/F24)
    /// the plain detector-override patterns, with a key this store generates and stores (G-34). When there are values to
    /// seal and the key store does not answer, the sealing migration waits: the file stays below it with its rows
    /// untouched, the Journal still opens, and what that migration seals reads as unavailable (never as its plain value)
    /// until a later read or write applies it (`ensureSealed`). Returns the version reached and the key, if one was made.
    private static func migrate(_ db: SQLiteConnection, now: Date, ruleKeys: any RuleKeyStore, backupsRoot: URL,
                                schemaFault: SchemaMigrationBackup.Fault?) throws -> (version: Int, key: SymmetricKey?) {
        let current = try db.tableExists("schema_version") ? db.scalarInt("SELECT coalesce(max(version), 0) FROM schema_version") : 0
        let latest = Migrations.latestVersion
        if current > latest { throw JournalError.newerSchema(found: current, supported: latest) }
        let (applied, key) = try applyPending(db, from: current, now: now, ruleKeys: ruleKeys, key: nil, backupsRoot: backupsRoot,
                                              schemaFault: schemaFault)
        return (applied, key)
    }

    /// G-40 (schema 10): from this version the `unchecked` table has `settled_at` and the `unread_spots` table exists.
    static let unreadSpotsVersion = 10

    /// G-26 for a table-rebuilding migration (`SchemaMigrationBackup`): the copy for the step, or nil when the file is new
    /// (nothing to keep) or the migration is not one that gets a copy. Throws when a copy is owed and cannot be made.
    /// `opened`: the schema the file had when it was opened; a file created now (0) has nothing to keep.
    private static func backupBefore(_ version: Int, db: SQLiteConnection, from current: Int, opened: Int, backupsRoot: URL, now: Date,
                                     fault: SchemaMigrationBackup.Fault?) throws -> URL? {
        guard SchemaMigrationBackup.backedUpVersions.contains(version), opened >= 1 else { return nil }
        try fault?(.copying)
        let backup = try SchemaMigrationBackup.prepare(db: db, backupsRoot: backupsRoot, from: current, to: version, now: now)
        try fault?(.copied)
        return backup
    }

    /// Every migration above `current`, in order. A sealing migration (8, 9) first gets a key when it has values to seal
    /// and none is in hand; if the key store does not answer, it and everything after it wait. An existing file that
    /// held plain secrets (below 9: hashes before 7, rule values before 8, patterns before 9) runs with secure_delete on
    /// and is scrubbed afterwards.
    /// G-26 (schema 10, G-40): a migration that rebuilds a table the person's rows live in first gets a copy of the file
    /// as it stands just before it (`SchemaMigrationBackup`: after 8 and 9 sealed every plain value, so the copy holds
    /// none); without a copy it and everything after it wait, like a sealing migration without its key.
    private static func applyPending(_ db: SQLiteConnection, from current: Int, now: Date, ruleKeys: any RuleKeyStore,
                                     key initial: SymmetricKey?, backupsRoot: URL,
                                     schemaFault: SchemaMigrationBackup.Fault? = nil) throws -> (version: Int, key: SymmetricKey?) {
        var applied = current
        var key = initial
        let scrubs = current >= 1 && current < sealedOverridesVersion
        if scrubs { try db.exec("PRAGMA secure_delete = ON") }
        defer { if scrubs { try? db.exec("PRAGMA secure_delete = OFF") } }
        for migration in Migrations.all where migration.version > current {
            if sealingVersions.contains(migration.version), key == nil, try hasValuesToSeal(db, version: migration.version) {
                do {
                    key = try freshKey(ruleKeys)
                } catch {
                    Log.journal.error("values wait to be sealed at schema=\(migration.version): the key store did not answer; they read as unavailable until it does")
                    break
                }
            }
            let backup: URL?
            do {
                backup = try backupBefore(migration.version, db: db, from: applied, opened: current, backupsRoot: backupsRoot, now: now,
                                          fault: schemaFault)
            } catch {
                Log.journal.error("schema \(migration.version) waits: its backup could not be written; the Journal stays at schema \(applied)")
                break
            }
            try applyMigration(migration, db: db, key: key, now: now)
            applied = migration.version
            if let backup {
                try schemaFault?(.migrated)
                SchemaMigrationBackup.verify(backup, db: db, now: now)
            }
        }
        if scrubs && applied > current {
            try scrub(db)
            Log.journal.info("journal database rewritten after migrating from=\(current) to=\(applied)")
        }
        return (applied, key)
    }

    private static func applyMigration(_ migration: (version: Int, sql: String), db: SQLiteConnection, key: SymmetricKey?, now: Date) throws {
        try db.transaction {
            try db.exec(Self.stripPragmas(migration.sql))
            if migration.version == sealedRulesVersion { try sealPlainRules(db, key: key) }
            if migration.version == sealedOverridesVersion { try sealPlainOverrides(db, key: key) }
            try db.run("INSERT INTO schema_version (version, applied_at) VALUES (?, ?)",
                       [.integer(Int64(migration.version)), .text(ISO.string(now))])
        }
    }

    /// The schema version from which no hash of a secret is stored (`007_drop_text_hash.sql`).
    static let scrubbedHashesVersion = 7
    /// The schema version from which every rule value is sealed (`008_seal_rule_values.sql`, G-30).
    static let sealedRulesVersion = 8
    /// The schema version from which every detector-override pattern list is sealed (`009_seal_detector_overrides.sql`,
    /// scan F15/F24).
    static let sealedOverridesVersion = 9
    static let sealingVersions: Set<Int> = [sealedRulesVersion, sealedOverridesVersion]

    /// Whether a sealing migration has plain values to seal (a Journal without rules or overrides never asks for a key).
    private static func hasValuesToSeal(_ db: SQLiteConnection, version: Int) throws -> Bool {
        switch version {
        case sealedRulesVersion: return try db.scalarInt("SELECT count(*) FROM rules") > 0
        case sealedOverridesVersion: return try db.scalarInt("SELECT count(*) FROM detector_overrides") > 0
        default: return false
        }
    }

    /// A new key, generated here and stored under its id (G-34: never one the key store already held). Throws when the
    /// key store cannot be asked.
    private static func freshKey(_ ruleKeys: any RuleKeyStore) throws -> SymmetricKey {
        let key = SymmetricKey(size: .bits256)
        try ruleKeys.store(key, id: RuleSeal.keyID(key))
        Log.journal.info("rule key created")
        return key
    }

    /// Schema 8's middle step, inside its transaction: every plain row of `rules` sealed into `rules_v8`, every other
    /// column copied as it is, then the old table dropped and the new one renamed.
    private static func sealPlainRules(_ db: SQLiteConnection, key: SymmetricKey?) throws {
        struct Plain {
            let id: String, action: RuleAction, kind: RuleKind, value: String, tokenLength: Int?, name: String?, enabled: Bool
            let createdAt: String, sortOrder: Int64
        }
        let rows = try db.query("SELECT id, action, kind, value, token_length, name, enabled, created_at, sort_order FROM rules", []) { r in
            guard let action = RuleAction(rawValue: r.string(1)), let kind = RuleKind(rawValue: r.string(2)) else {
                throw JournalError.corruptRecord("rule \(r.string(0))")
            }
            return Plain(id: r.string(0), action: action, kind: kind, value: r.string(3), tokenLength: r.optionalInt(4), name: r.optionalString(5),
                         enabled: r.bool(6), createdAt: r.string(7), sortOrder: r.int64(8))
        }
        if !rows.isEmpty {
            guard let key else { throw JournalError.ruleKeyUnavailable }
            for row in rows {
                let sealed = try RuleSeal.seal(row.value, id: row.id, action: row.action, kind: row.kind, key: key)
                try db.run("""
                    INSERT INTO rules_v8 (id, action, kind, sealed_value, token_length, name, enabled, created_at, sort_order)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """, [.text(row.id), .text(row.action.rawValue), .text(row.kind.rawValue), .blob(sealed), SQLValue(row.tokenLength),
                          SQLValue(row.name), SQLValue(row.enabled), .text(row.createdAt), .integer(row.sortOrder)])
            }
        }
        try db.exec(Migrations.sealRuleValues008Finish)
        Log.journal.info("rule values sealed count=\(rows.count)")
    }

    /// Schema 9's middle step, inside its transaction: every plain row of `detector_overrides` sealed into
    /// `detector_overrides_v9`, then the old table dropped and the new one renamed.
    private static func sealPlainOverrides(_ db: SQLiteConnection, key: SymmetricKey?) throws {
        let rows = try db.query("SELECT detector_id, specs_json, updated_at FROM detector_overrides", []) { r in
            (id: r.string(0), specs: r.string(1), updatedAt: r.string(2))
        }
        if !rows.isEmpty {
            guard let key else { throw JournalError.ruleKeyUnavailable }
            for row in rows {
                let sealed = try OverrideSeal.seal(row.specs, detectorID: row.id, key: key)
                try db.run("INSERT INTO detector_overrides_v9 (detector_id, sealed_specs, updated_at) VALUES (?, ?, ?)",
                           [.text(row.id), .blob(sealed), .text(row.updatedAt)])
            }
        }
        try db.exec(Migrations.sealDetectorOverrides009Finish)
        Log.journal.info("detector overrides sealed count=\(rows.count)")
    }

    /// Rewrites the file so its freed pages and its log hold nothing that was deleted: with secure_delete on (the caller
    /// sets it) freed pages are zeroed, the VACUUM rewrites the file, and the WAL, which held the old pages too, is
    /// checkpointed and truncated to nothing.
    private static func scrub(_ db: SQLiteConnection) throws {
        try db.exec("PRAGMA wal_checkpoint(TRUNCATE)")
        try db.exec("VACUUM")
        try db.exec("PRAGMA wal_checkpoint(TRUNCATE)")
    }

    /// Applies the sealing migrations that had to wait for the key store at open (G-30, F15). True once the file is at
    /// the latest schema; false while the key store still does not answer (nothing changed, or only what needed no key).
    /// Another process may have migrated the file meanwhile; that counts too.
    @discardableResult
    private func ensureSealed() throws -> Bool {
        if schemaVersion >= Migrations.latestVersion { return true }
        let current = try db.scalarInt("SELECT coalesce(max(version), 0) FROM schema_version")
        let (applied, key) = try Self.applyPending(db, from: current, now: clock.now(), ruleKeys: ruleKeys, key: sessionKey, backupsRoot: backupsRoot,
                                                   schemaFault: schemaFault)
        if let key, sessionKey == nil {
            sessionKey = key
            openedKeys[RuleSeal.keyID(key)] = key
        }
        schemaVersion = applied
        if applied < Migrations.latestVersion { Log.journal.error("values still wait to be sealed: the key store did not answer") }
        return applied >= Migrations.latestVersion
    }

    /// PRAGMAs are connection settings (set by SQLiteConnection) and cannot run inside the migration transaction.
    static func stripPragmas(_ sql: String) -> String {
        sql.split(separator: "\n", omittingEmptySubsequences: false)
            .filter { !$0.trimmingCharacters(in: .whitespaces).uppercased().hasPrefix("PRAGMA ") }
            .joined(separator: "\n")
    }

    private static func restrictDatabaseFiles(at url: URL) throws {
        for suffix in ["", "-wal", "-shm"] {
            let path = url.path + suffix
            if FileManager.default.fileExists(atPath: path) {
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: path)
            }
        }
    }

    private static func ensureDefaultStyle(_ db: SQLiteConnection) throws {
        if try db.scalarInt("SELECT count(*) FROM styles WHERE is_default = 1") == 0 {
            _ = try insertStyle(StyleRecord.builtInDefault, isDefault: true, into: db)
        }
    }

    // MARK: - Paths

    static func fileExtension(for uti: String) throws -> String {
        switch uti {
        case "public.png": return "png"
        case "public.jpeg": return "jpg"
        case "public.heic": return "heic"
        default: throw JournalError.unsupportedContainer(uti)
        }
    }

    nonisolated var trashRoot: URL { journalRoot.appendingPathComponent(Self.trashFolderName, isDirectory: true) }
    /// Where a new or moved-in entry's folder goes.
    nonisolated func liveFolder(_ id: UUID) -> URL { journalRoot.appendingPathComponent(id.uuidString, isDirectory: true) }
    nonisolated func trashFolder(_ id: UUID) -> URL { trashRoot.appendingPathComponent(id.uuidString, isDirectory: true) }

    /// The entry's live folder as it is on disk: `Journal.noindex`, or the old `Journal` folder when a stopped layout
    /// migration left it there (G-23), so the entry stays readable (and is not swept as stale) until the move finishes.
    private func existingLiveFolder(_ id: UUID) -> URL {
        let current = liveFolder(id)
        if fm.fileExists(atPath: current.path) { return current }
        let legacy = legacyJournalRoot.appendingPathComponent(id.uuidString, isDirectory: true)
        return fm.fileExists(atPath: legacy.path) ? legacy : current
    }

    private func existingTrashFolder(_ id: UUID) -> URL {
        let current = trashFolder(id)
        if fm.fileExists(atPath: current.path) { return current }
        let legacy = legacyJournalRoot.appendingPathComponent(Self.trashFolderName, isDirectory: true)
            .appendingPathComponent(id.uuidString, isDirectory: true)
        return fm.fileExists(atPath: legacy.path) ? legacy : current
    }

    private func folder(for entry: Entry) -> URL { entry.isTrashed ? existingTrashFolder(entry.id) : existingLiveFolder(entry.id) }

    private func fileURL(_ entryID: UUID, name: String) throws -> URL {
        let e = try entry(entryID)
        let ext = try Self.fileExtension(for: e.containerUTI)
        return folder(for: e).appendingPathComponent("\(name).\(ext)")
    }

    public func originalURL(_ entryID: UUID) throws -> URL { try fileURL(entryID, name: "original") }

    /// The clean file, only while it is the one its row was committed with (G-28).
    public func cleanURL(_ entryID: UUID) throws -> URL {
        let url = try fileURL(entryID, name: "clean")
        _ = try verifiedClean(entryID, at: url)
        return url
    }

    public func originalData(_ entryID: UUID) throws -> Data { try read(originalURL(entryID)) }
    public func cleanData(_ entryID: UUID) throws -> Data { try verifiedClean(entryID, at: fileURL(entryID, name: "clean")) }

    public func cleanImage(_ entryID: UUID) throws -> CleanImage {
        // One actor turn, no await: no commit can land between the row and the bytes.
        let e = try entry(entryID)
        let data = try verifiedClean(entryID, at: folder(for: e).appendingPathComponent("clean.\(try Self.fileExtension(for: e.containerUTI))"))
        return CleanImage(entry: e, data: data)
    }

    /// The clean file's bytes when they match the digest the row was committed with; `cleanOutOfDate` when the row has
    /// no digest (an entry from before schema 6, not re-rendered yet) or the bytes differ (a crash between the file and
    /// the row, or a file changed behind the store).
    private func verifiedClean(_ entryID: UUID, at url: URL) throws -> Data {
        let data = try read(url)
        guard let digest = try storedDigest(entryID), digest == Self.digest(data) else {
            Log.journal.error("clean picture refused: it does not match its row entry=\(entryID.uuidString, privacy: .public)")
            throw JournalError.cleanOutOfDate(entryID)
        }
        return data
    }

    private func storedDigest(_ entryID: UUID) throws -> String? {
        try db.first("SELECT clean_sha256 FROM entries WHERE id = ?", [.text(entryID.uuidString)]) { $0.optionalString(0) } ?? nil
    }

    /// SHA-256 of a whole image file, lowercase hex. Never of recognized text.
    static func digest(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }

    private func read(_ url: URL) throws -> Data {
        guard fm.fileExists(atPath: url.path) else { throw JournalError.fileMissing(url) }
        return try Data(contentsOf: url)
    }

    private func removeFolderIfPresent(_ url: URL) throws {
        if fm.fileExists(atPath: url.path) { try fm.removeItem(at: url) }
    }

    // MARK: - Entries

    public func create(_ entry: NewEntry, original: Data, clean: Data) throws -> Entry {
        let id = UUID()
        let ext = try Self.fileExtension(for: entry.containerUTI)
        let folder = liveFolder(id)
        try FileAtomics.makePrivateDirectory(folder)
        do {
            try FileAtomics.write(original, to: folder.appendingPathComponent("original.\(ext)"), mode: .privateToUser)
            try FileAtomics.write(clean, to: folder.appendingPathComponent("clean.\(ext)"), mode: .privateToUser)
            try db.transaction {
                let styleID: Int64
                if let style = entry.style {
                    styleID = try insertStyle(style, isDefault: false)
                } else {
                    styleID = try defaultStyle().id ?? { throw JournalError.corruptRecord("default style has no id") }()
                }
                try db.run("""
                    INSERT INTO entries (id, created_at, source, display_name, file_path, clean_copy_path, container_uti,
                                         pixel_width, pixel_height, revision, style_id, trashed_at, clean_sha256)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?, NULL, ?)
                    """, [.text(id.uuidString), .text(ISO.string(clock.now())), .text(entry.source.rawValue), .text(entry.displayName),
                          SQLValue(entry.filePath), SQLValue(entry.cleanCopyPath), .text(entry.containerUTI),
                          .integer(Int64(entry.pixelWidth)), .integer(Int64(entry.pixelHeight)), .integer(styleID), .text(Self.digest(clean))])
                try insertFindings(entry.findings, entryID: id)
            }
        } catch {
            try? fm.removeItem(at: folder)
            throw error
        }
        return try self.entry(id)
    }

    private func insertFindings(_ findings: [NewFinding], entryID: UUID) throws {
        for f in findings {
            let ids = try JSONEncoder().encode(f.detectorIDs)
            try db.run("""
                INSERT INTO findings (id, entry_id, line_index, rect_x, rect_y, rect_w, rect_h, detector_ids, category, enabled)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, [.text(UUID().uuidString), .text(entryID.uuidString), .integer(Int64(f.lineIndex)),
                      .real(f.rect.origin.x), .real(f.rect.origin.y), .real(f.rect.width), .real(f.rect.height),
                      .text(String(decoding: ids, as: UTF8.self)), .text(f.category), SQLValue(f.enabled)])
        }
    }

    public func entry(_ id: UUID) throws -> Entry {
        guard let e = try loadEntries(where: "e.id = ?", [.text(id.uuidString)], tail: "").first else { throw JournalError.entryNotFound(id) }
        return e
    }

    public func entries(matching query: EntryQuery) throws -> [Entry] {
        var clauses: [String] = []
        var binds: [SQLValue] = []
        switch query.trashed {
        case .some(true): clauses.append("e.trashed_at IS NOT NULL")
        case .some(false): clauses.append("e.trashed_at IS NULL")
        case .none: break
        }
        if let s = query.search?.trimmingCharacters(in: .whitespaces), !s.isEmpty {
            clauses.append("e.display_name LIKE ? ESCAPE '\\'")
            let escaped = s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "%", with: "\\%").replacingOccurrences(of: "_", with: "\\_")
            binds.append(.text("%\(escaped)%"))
        }
        if let from = query.from { clauses.append("e.created_at >= ?"); binds.append(.text(ISO.string(from))) }
        if let to = query.to { clauses.append("e.created_at < ?"); binds.append(.text(ISO.string(to))) }
        var tail = ""
        if let limit = query.limit { tail = " LIMIT \(max(0, limit)) OFFSET \(max(0, query.offset))" }
        else if query.offset > 0 { tail = " LIMIT -1 OFFSET \(query.offset)" }
        return try loadEntries(where: clauses.isEmpty ? "1" : clauses.joined(separator: " AND "), binds, tail: tail)
    }

    private static let entrySelect = """
        SELECT e.id, e.created_at, e.source, e.display_name, e.file_path, e.clean_copy_path, e.container_uti,
               e.pixel_width, e.pixel_height, e.revision, e.trashed_at,
               s.id, s.kind, s.color_rgba, s.roundness, s.padding, s.label_mode, s.is_default
        FROM entries e JOIN styles s ON s.id = e.style_id
        """

    private func loadEntries(where filter: String, _ binds: [SQLValue], tail: String) throws -> [Entry] {
        try Self.loadEntries(db, where: filter, binds, tail: tail)
    }

    /// Also used by `JournalInspector` on a read-only connection.
    static func loadEntries(_ db: SQLiteConnection, where filter: String, _ binds: [SQLValue], tail: String) throws -> [Entry] {
        struct Partial { let id: UUID; let row: (Date, EntrySource, String, String?, String?, String, Int, Int, Int, Date?, StyleRecord) }
        let partials: [Partial] = try db.query(Self.entrySelect + " WHERE \(filter) ORDER BY e.created_at DESC, e.id DESC" + tail, binds) { r in
            guard let id = UUID(uuidString: r.string(0)) else { throw JournalError.corruptRecord("entry id \(r.string(0))") }
            guard let source = EntrySource(rawValue: r.string(2)) else { throw JournalError.corruptRecord("entry source \(r.string(2))") }
            let style = try Self.style(from: r, at: 11)
            return Partial(id: id, row: (try ISO.date(r.string(1)), source, r.string(3), r.optionalString(4), r.optionalString(5), r.string(6),
                                         r.int(7), r.int(8), r.int(9), try r.optionalString(10).map(ISO.date), style))
        }
        guard !partials.isEmpty else { return [] }
        let findingsSQL = """
            SELECT f.id, f.entry_id, f.line_index, f.rect_x, f.rect_y, f.rect_w, f.rect_h, f.detector_ids, f.category, f.enabled
            FROM findings f WHERE f.entry_id IN (SELECT e.id FROM entries e WHERE \(filter) ORDER BY e.created_at DESC, e.id DESC\(tail))
            ORDER BY f.line_index, f.rect_x
            """
        var byEntry: [UUID: [Finding]] = [:]
        for f in try db.query(findingsSQL, binds, Self.finding(from:)) { byEntry[f.entryID, default: []].append(f) }
        return partials.map { p in
            let (createdAt, source, name, filePath, cleanCopy, uti, w, h, rev, trashedAt, style) = p.row
            return Entry(id: p.id, createdAt: createdAt, source: source, displayName: name, filePath: filePath, cleanCopyPath: cleanCopy,
                         containerUTI: uti, pixelWidth: w, pixelHeight: h, revision: rev, style: style, trashedAt: trashedAt,
                         findings: byEntry[p.id] ?? [])
        }
    }

    private static func finding(from r: SQLiteConnection.Row) throws -> Finding {
        guard let id = UUID(uuidString: r.string(0)), let entryID = UUID(uuidString: r.string(1)) else {
            throw JournalError.corruptRecord("finding ids \(r.string(0)) / \(r.string(1))")
        }
        let ids = try JSONDecoder().decode([String].self, from: Data(r.string(7).utf8))
        return Finding(id: id, entryID: entryID, lineIndex: r.int(2),
                       rect: CGRect(x: r.double(3), y: r.double(4), width: r.double(5), height: r.double(6)),
                       detectorIDs: ids, category: r.string(8), enabled: r.bool(9))
    }

    private static func style(from r: SQLiteConnection.Row, at c: Int) throws -> StyleRecord {
        guard let kind = StyleKind(rawValue: r.string(c + 1)), let label = LabelMode(rawValue: r.string(c + 5)) else {
            throw JournalError.corruptRecord("style \(r.int64(c))")
        }
        return StyleRecord(id: r.int64(c), kind: kind, color: r.string(c + 2), roundness: r.double(c + 3), padding: r.double(c + 4),
                           labelMode: label, isDefault: r.bool(c + 6))
    }

    public func addVisibleFindings(_ entryID: UUID, _ findings: [NewFinding], expectedRevision: Int) throws -> Entry {
        let e = try entry(entryID)
        guard e.revision == expectedRevision else { throw JournalError.revisionConflict(entryID) }
        try db.transaction {
            try insertFindings(findings.map { var f = $0; f.enabled = false; return f }, entryID: entryID)
            try db.run("UPDATE entries SET revision = revision + 1 WHERE id = ? AND revision = ?",
                       [.text(entryID.uuidString), .integer(Int64(expectedRevision))])
            if db.changes != 1 { throw JournalError.revisionConflict(entryID) }
        }
        Log.journal.info("findings added left visible count=\(findings.count)")
        return try entry(entryID)
    }

    public func commitRender(_ entryID: UUID, clean: Data, enabled: Set<UUID>, style: StyleRecord?, expectedRevision: Int) throws -> Entry {
        let e = try entry(entryID)
        guard e.revision == expectedRevision else { throw JournalError.revisionConflict(entryID) }
        let known = Set(e.findings.map(\.id))
        if let unknown = enabled.subtracting(known).first { throw JournalError.findingNotFound(unknown) }
        let url = folder(for: e).appendingPathComponent("clean.\(try Self.fileExtension(for: e.containerUTI))")
        let previous = fm.fileExists(atPath: url.path) ? try Data(contentsOf: url) : nil
        // File first, then the rows in one transaction. Until the rows land, the row's digest still names the previous
        // file, so a read in between (or after a crash) is refused rather than trusted; a failure puts the previous file
        // back, and if even that fails, the mismatch keeps every read refusing until the engine renders it again.
        try FileAtomics.write(clean, to: url, mode: .privateToUser)
        do {
            if commitFault != nil { throw JournalError.sqlite(code: -1, message: "injected failure after the file") }
            try db.transaction {
                for f in e.findings where f.enabled != enabled.contains(f.id) {
                    try db.run("UPDATE findings SET enabled = ? WHERE id = ?", [SQLValue(enabled.contains(f.id)), .text(f.id.uuidString)])
                }
                if let style {
                    let styleID = try insertStyle(style, isDefault: false)
                    try db.run("UPDATE entries SET style_id = ? WHERE id = ?", [.integer(styleID), .text(e.id.uuidString)])
                    if !e.style.isDefault {
                        try db.run("DELETE FROM styles WHERE id = ? AND is_default = 0 AND NOT EXISTS (SELECT 1 FROM entries WHERE style_id = ?)",
                                   [.integer(e.style.id ?? -1), .integer(e.style.id ?? -1)])
                    }
                }
                try db.run("UPDATE entries SET revision = revision + 1, clean_sha256 = ? WHERE id = ? AND revision = ?",
                           [.text(Self.digest(clean)), .text(e.id.uuidString), .integer(Int64(expectedRevision))])
                if db.changes != 1 { throw JournalError.revisionConflict(entryID) }
            }
        } catch {
            if let previous, commitFault != .afterFileWriteAndRestore {
                do { try FileAtomics.write(previous, to: url, mode: .privateToUser) } catch {
                    Log.journal.error("clean picture not put back after a failed change; reads refuse it until re-rendered")
                }
            }
            throw error
        }
        return try entry(entryID)
    }

    public func entriesNeedingRender() throws -> [UUID] {
        var out: [UUID] = []
        for e in try entries(matching: .live) {
            let url = folder(for: e).appendingPathComponent("clean.\(try Self.fileExtension(for: e.containerUTI))")
            guard fm.fileExists(atPath: url.path) else { continue }   // a missing file is the stale sweep's
            let current = try storedDigest(e.id)
            let onDisk = Self.digest(try Data(contentsOf: url))
            if current != onDisk { out.append(e.id) }
        }
        return out
    }

    /// Each entry is tried, past a failure (fail-open #12); the first failure is thrown at the end, so a caller reads
    /// back which ones moved rather than assuming all or none did.
    public func trash(_ ids: [UUID]) throws {
        guard !ids.isEmpty else { return }
        try JournalPathSafety.checkContained(trashRoot, in: root, what: "trash folder")
        try FileAtomics.makePrivateDirectory(trashRoot)
        let now = ISO.string(clock.now())
        var firstError: (any Error)?
        for id in ids {
            do {
                let e = try entry(id)
                guard !e.isTrashed else { continue }
                let destination = trashFolder(id)
                let source = existingLiveFolder(id)
                try removeFolderIfPresent(destination)
                try fm.moveItem(at: source, to: destination)
                do {
                    try db.run("UPDATE entries SET trashed_at = ? WHERE id = ?", [.text(now), .text(id.uuidString)])
                } catch {
                    try? fm.moveItem(at: destination, to: source)
                    throw error
                }
            } catch {
                firstError = firstError ?? error
            }
        }
        if let firstError { throw firstError }
    }

    /// Each entry is tried, past a failure (fail-open #12); the first failure is thrown at the end.
    public func restore(_ ids: [UUID]) throws {
        var firstError: (any Error)?
        for id in ids {
            do {
                let e = try entry(id)
                guard e.isTrashed else { continue }
                let source = existingTrashFolder(id)
                guard fm.fileExists(atPath: source.path) else { throw JournalError.fileMissing(source) }
                let destination = liveFolder(id)
                try removeFolderIfPresent(destination)
                try fm.moveItem(at: source, to: destination)
                do {
                    try db.run("UPDATE entries SET trashed_at = NULL WHERE id = ?", [.text(id.uuidString)])
                } catch {
                    try? fm.moveItem(at: destination, to: source)
                    throw error
                }
            } catch {
                firstError = firstError ?? error
            }
        }
        if let firstError { throw firstError }
    }

    public func purgeTrash() throws {
        let failed = try Self.purgeTrash(db, root: root, trashRoots: [trashRoot,legacyJournalRoot.appendingPathComponent(Self.trashFolderName, isDirectory: true)])
        if failed > 0 { throw JournalError.maintenanceIncomplete(step: "trash", failed: failed) }
    }

    /// Fail-open #11: per trashed entry, its folders first and then its row, going on past a failure; then anything left
    /// under the trash folders, which no row names. A folder that will not go keeps its row, so the entry is tried again
    /// at the next prune and no original is ever left on disk with nothing pointing at it. Returns how many could not be
    /// removed.
    ///
    /// F2: a row's id becomes a folder name only as the canonical text of a parsed UUID (a row whose id is not one is
    /// left alone and counted; nothing on disk is touched for it), and a trash folder that is a link or resolves outside
    /// `root` is never entered (counted; its rows stay for the next try).
    private static func purgeTrash(_ db: SQLiteConnection, root: URL, trashRoots: [URL]) throws -> Int {
        let fm = FileManager.default
        var failed = 0
        var kept: Set<String> = []
        var usable: [URL] = []
        for trashRoot in trashRoots {
            do {
                try JournalPathSafety.checkContained(trashRoot, in: root, what: "trash folder")
                usable.append(trashRoot)
            } catch {
                failed += 1
                Log.journal.error("trash folder skipped: it is a link or lies outside the Journal")
            }
        }
        let ids = try db.query("SELECT id FROM entries WHERE trashed_at IS NOT NULL", []) { $0.string(0) }
        var rejected = 0
        for id in ids {
            guard let name = JournalPathSafety.entryFolderName(id) else {
                rejected += 1
                continue
            }
            do {
                // A trash folder that could not be used may still hold this entry's folder: the row stays then.
                guard usable.count == trashRoots.count else { throw JournalError.unsafeLocation("trash folder") }
                for trashRoot in usable {
                    let folder = trashRoot.appendingPathComponent(name, isDirectory: true)
                    // Removed as itself: a link here goes, never what it points at.
                    if JournalPathSafety.kind(folder) != .missing { try fm.removeItem(at: folder) }
                }
                try db.run("DELETE FROM entries WHERE id = ?", [.text(id)])
            } catch {
                failed += 1
                kept.insert(name)
            }
        }
        if rejected > 0 {
            failed += rejected
            Log.journal.error("trash purge skipped rows whose id is not an entry id count=\(rejected); nothing on disk was touched for them")
        }
        try db.run("DELETE FROM styles WHERE is_default = 0 AND NOT EXISTS (SELECT 1 FROM entries WHERE style_id = styles.id)")
        for trashRoot in usable where JournalPathSafety.kind(trashRoot) == .directory {
            do {
                // Each item is removed as itself: a link inside the trash goes, never what it points at.
                for item in try fm.contentsOfDirectory(at: trashRoot, includingPropertiesForKeys: nil, options: [])
                where !kept.contains(item.lastPathComponent) {
                    do { try fm.removeItem(at: item) } catch { failed += 1 }
                }
                if try fm.contentsOfDirectory(atPath: trashRoot.path).isEmpty { try fm.removeItem(at: trashRoot) }
            } catch {
                failed += 1
            }
        }
        if failed > 0 { Log.journal.error("trash purge incomplete failed=\(failed); tried again at the next prune") }
        return failed
    }

    /// Fail-open #11: every step runs and every entry is tried, past any failure; a failure anywhere is thrown at the
    /// end (`maintenanceIncomplete`), so the engine shows it instead of the prune quietly stopping at the first one.
    public func pruneExpired(olderThan: Duration) throws -> Int {
        var failed = 0
        do { try purgeTrash() } catch JournalError.maintenanceIncomplete(_, let n) { failed += n }
        let cutoff = clock.now().addingTimeInterval(-olderThan.seconds)
        let ids: [UUID] = try db.query("SELECT id FROM entries WHERE trashed_at IS NULL AND created_at < ?", [.text(ISO.string(cutoff))]) { r in
            guard let id = UUID(uuidString: r.string(0)) else { throw JournalError.corruptRecord("entry id \(r.string(0))") }
            return id
        }
        var pruned = 0
        for id in ids {
            do { try deleteEntry(id); pruned += 1 } catch { failed += 1 }
        }
        // The layout migration's verified backup holds originals too: it goes once the same window has passed (G-23).
        var backups = 0
        do { backups = try JournalLayoutMigration.pruneVerifiedBackups(in: backupsRoot, takenBefore: cutoff) } catch { failed += 1 }
        // G-26 for schema 10 (G-40): a verified copy of the database taken before a migration goes after the same window.
        do { backups += try SchemaMigrationBackup.pruneVerified(in: backupsRoot, takenBefore: cutoff) } catch { failed += 1 }
        // G-40: the record of a settled spot row (a path, rects, how it was settled) follows the Journal's retention too.
        do { try pruneSettledSpots(before: cutoff) } catch { failed += 1 }
        Log.journal.info("pruned \(pruned) expired entries backups=\(backups) failed=\(failed)")
        if failed > 0 { throw JournalError.maintenanceIncomplete(step: "prune", failed: failed) }
        return pruned
    }

    public func sweepStale() throws -> Int {
        var removed = 0, failed = 0
        for e in try entries(matching: .live) {
            let ext = try Self.fileExtension(for: e.containerUTI)
            let folder = existingLiveFolder(e.id)
            let present = ["original", "clean"].allSatisfy { fm.fileExists(atPath: folder.appendingPathComponent("\($0).\(ext)").path) }
            guard !present else { continue }
            do { try deleteEntry(e.id); removed += 1 } catch { failed += 1 }
        }
        Log.journal.info("swept \(removed) stale entries failed=\(failed)")
        if failed > 0 { throw JournalError.maintenanceIncomplete(step: "sweep", failed: failed) }
        return removed
    }

    /// Fail-open #11: entry folders in `Journal.noindex` (and its trash) that no row names, left by a crash or by a
    /// delete that removed the row but not the folder, are removed: an original nothing lists is still an original. Only
    /// folders named by an entry id are touched; the pre-G-23 folder is the layout migration's. Returns how many went.
    public func sweepOrphans() throws -> Int {
        let known = Set(try db.query("SELECT id FROM entries", []) { r in UUID(uuidString: r.string(0)) }.compactMap { $0 })
        var removed = 0, failed = 0
        for folder in [journalRoot, trashRoot] where fm.fileExists(atPath: folder.path) {
            // F2: never enumerated through a link.
            guard (try? JournalPathSafety.checkContained(folder, in: root, what: "folder")) != nil else { failed += 1; continue }
            let items: [URL]
            do { items = try fm.contentsOfDirectory(at: folder, includingPropertiesForKeys: [.isDirectoryKey], options: []) } catch {
                failed += 1
                continue
            }
            for item in items {
                guard let id = UUID(uuidString: item.lastPathComponent), !known.contains(id),
                      (try? item.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) == true else { continue }
                do { try fm.removeItem(at: item); removed += 1 } catch { failed += 1 }
            }
        }
        Log.journal.info("orphan folders removed=\(removed) failed=\(failed)")
        if failed > 0 { throw JournalError.maintenanceIncomplete(step: "orphans", failed: failed) }
        return removed
    }

    /// Folders first, then the row (fail-open #11): a crash or a failure part-way leaves the row, so the entry is still
    /// listed, still swept when a file is missing, and tried again at the next prune; never an original with no row.
    private func deleteEntry(_ id: UUID) throws {
        for folder in [existingLiveFolder(id), liveFolder(id), existingTrashFolder(id), trashFolder(id)] { try removeFolderIfPresent(folder) }
        try db.transaction {
            try db.run("DELETE FROM entries WHERE id = ?", [.text(id.uuidString)])
            try db.run("DELETE FROM styles WHERE is_default = 0 AND NOT EXISTS (SELECT 1 FROM entries WHERE style_id = styles.id)")
        }
    }

    /// Every image folder first, going on past a failure, then the rows of the entries whose folders are gone (#11);
    /// anything that would not go is thrown at the end and keeps its row for the next try.
    public func deleteAll() throws {
        var failed = 0
        if fm.fileExists(atPath: journalRoot.path) {
            try JournalPathSafety.checkContained(journalRoot, in: root, what: "images folder")
            for item in try fm.contentsOfDirectory(at: journalRoot, includingPropertiesForKeys: nil, options: []) {
                do { try fm.removeItem(at: item) } catch { failed += 1 }
            }
        }
        // Every other copy of an original Obscura made: a folder a stopped migration left behind, and its backups.
        do { try removeFolderIfPresent(legacyJournalRoot) } catch { failed += 1 }
        // A schema backup (G-40's schema 10) holds the database only, no original: it is left to its own pruning.
        for backup in JournalLayoutMigration.allBackups(in: backupsRoot) {
            do { try fm.removeItem(at: backup) } catch { failed += 1 }
        }
        let ids: [UUID] = try db.query("SELECT id FROM entries", []) { r in UUID(uuidString: r.string(0)) }.compactMap { $0 }
        try db.transaction {
            for id in ids {
                let folders = [existingLiveFolder(id), liveFolder(id), existingTrashFolder(id), trashFolder(id)]
                guard !folders.contains(where: { fm.fileExists(atPath: $0.path) }) else { continue }
                try db.run("DELETE FROM entries WHERE id = ?", [.text(id.uuidString)])
            }
            try db.run("DELETE FROM styles WHERE is_default = 0 AND NOT EXISTS (SELECT 1 FROM entries WHERE style_id = styles.id)")
        }
        if failed > 0 { throw JournalError.maintenanceIncomplete(step: "deleteAll", failed: failed) }
    }

    // MARK: - Stats

    public func record(stat: StatEvent) throws {
        let now = clock.now()
        let day = LocalDay.key(now)
        try db.transaction {
            try db.run("INSERT OR IGNORE INTO stats_days (day) VALUES (?)", [.text(day)])
            switch stat {
            case .clean:
                try db.run("UPDATE stats_days SET checked = checked + 1 WHERE day = ?", [.text(day)])
            case .caught(let secrets, let categories):
                let current = try dayStats(day)
                var merged = current.categories
                for (k, v) in categories { merged[k, default: 0] += v }
                // A caught image was checked too: both counters move in one statement, so caught ≤ checked always holds.
                try db.run("UPDATE stats_days SET checked = checked + 1, caught = caught + 1, secrets = secrets + ?, categories_json = ? WHERE day = ?",
                           [.integer(Int64(secrets)), .text(try JSON.string(merged)), .text(day)])
            case .skipped(let reason):
                let current = try dayStats(day)
                var skipped = current.skipped
                skipped[reason, default: 0] += 1
                try db.run("UPDATE stats_days SET skipped_json = ? WHERE day = ?", [.text(try JSON.string(skipped)), .text(day)])
            }
            let keep = LocalDay.key(LocalDay.calendar.date(byAdding: .day, value: -Self.statsRetentionDays, to: now) ?? now)
            try db.run("DELETE FROM stats_days WHERE day < ?", [.text(keep)])
        }
    }

    private func dayStats(_ day: String) throws -> DayStats {
        try db.first("SELECT day, checked, caught, secrets, skipped_json, categories_json FROM stats_days WHERE day = ?", [.text(day)], Self.dayStats(from:))
            ?? DayStats(day: day)
    }

    private static func dayStats(from r: SQLiteConnection.Row) throws -> DayStats {
        DayStats(day: r.string(0), checked: r.int(1), caught: r.int(2), secrets: r.int(3),
                 skipped: try JSON.counts(r.string(4)), categories: try JSON.counts(r.string(5)))
    }

    public func weekStats() throws -> [DayStats] { try stats(days: 7) }

    public func stats(days: Int) throws -> [DayStats] {
        guard days > 0 else { return [] }
        let today = LocalDay.calendar.startOfDay(for: clock.now())
        let keys: [String] = (0..<days).reversed().map { LocalDay.key(LocalDay.calendar.date(byAdding: .day, value: -$0, to: today) ?? today) }
        let rows = try db.query("SELECT day, checked, caught, secrets, skipped_json, categories_json FROM stats_days WHERE day >= ? AND day <= ?",
                                [.text(keys.first ?? ""), .text(keys.last ?? "")], Self.dayStats(from:))
        let byDay = Dictionary(uniqueKeysWithValues: rows.map { ($0.day, $0) })
        return keys.map { byDay[$0] ?? DayStats(day: $0) }
    }

    // MARK: - Rules

    /// Every rule with its value opened, or the reason it could not be (G-30). An unreadable rule is listed, never left
    /// out and never read as anything but unreadable; the log names how many and their ids, never a value.
    public func rules() throws -> [StoredRule] {
        guard try ensureSealed() || schemaVersion >= Self.sealedRulesVersion else {
            // Schema 8 still waits for the key store: the old rows are not read at all, so no value is used unsealed.
            let waiting: [StoredRule] = try db.query("""
                SELECT id, action, kind, token_length, name, enabled, created_at, sort_order FROM rules ORDER BY sort_order, created_at
                """, []) { r in
                .unreadable(try Self.unreadable(from: r, problem: .keyUnavailable))
            }
            if !waiting.isEmpty { Log.journal.error("rules unreadable count=\(waiting.count) reason=keyUnavailable") }
            return waiting
        }
        return try loadRules()
    }

    /// The sealed rows opened with their keys; the file must be at schema 8 or later. Asks the key store only when there is a row.
    private func loadRules() throws -> [StoredRule] {
        struct Sealed { let rule: RuleRecord; let sealed: Data }
        let rows: [Sealed] = try db.query("""
            SELECT id, action, kind, token_length, name, enabled, created_at, sort_order, sealed_value FROM rules ORDER BY sort_order, created_at
            """, []) { r in
            let meta = try Self.unreadable(from: r, problem: .damaged)
            let sealed = r.isNull(8) ? Data() : r.data(8)
            return Sealed(rule: RuleRecord(id: meta.id, action: meta.action, kind: meta.kind, value: "", tokenLength: meta.tokenLength,
                                           name: meta.name, enabled: meta.enabled, createdAt: meta.createdAt, sortOrder: meta.sortOrder),
                          sealed: sealed)
        }
        guard !rows.isEmpty else { return [] }
        let out: [StoredRule] = rows.map { row in
            var rule = row.rule
            let opened = RuleSeal.open(row.sealed, id: rule.id, action: rule.action, kind: rule.kind, keys: { openingKey($0) })
            switch opened {
            case .success(let value):
                rule.value = value
                return .readable(rule)
            case .failure(let problem):
                return .unreadable(UnreadableRule(id: rule.id, action: rule.action, kind: rule.kind, tokenLength: rule.tokenLength, name: rule.name,
                                                  enabled: rule.enabled, createdAt: rule.createdAt, sortOrder: rule.sortOrder, problem: problem))
            }
        }
        let unreadable = out.compactMap(\.unreadable)
        if !unreadable.isEmpty {
            let ids = unreadable.map { "\($0.id):\($0.problem.rawValue)" }.joined(separator: ",")
            Log.journal.error("rules unreadable count=\(unreadable.count) of=\(out.count) ids=\(ids, privacy: .public)")
        }
        return out
    }

    /// Every column of a rules row but its value (columns 0...7: id, action, kind, token_length, name, enabled,
    /// created_at, sort_order).
    private static func unreadable(from r: SQLiteConnection.Row, problem: RuleValueProblem) throws -> UnreadableRule {
        guard let action = RuleAction(rawValue: r.string(1)), let kind = RuleKind(rawValue: r.string(2)) else {
            throw JournalError.corruptRecord("rule \(r.string(0))")
        }
        return UnreadableRule(id: r.string(0), action: action, kind: kind, tokenLength: r.optionalInt(3), name: r.optionalString(4),
                              enabled: r.bool(5), createdAt: try ISO.date(r.string(6)), sortOrder: r.int(7), problem: problem)
    }

    /// The key a sealed value names (G-34): this store's own, one handed over before, or the key store's when its bytes
    /// produce that id. None: `keyMissing` when the key store holds no key at all, `otherKey` when it holds others, and
    /// `keyUnavailable` when it cannot be asked.
    private func openingKey(_ id: Data) -> Result<SymmetricKey, RuleValueProblem> {
        if let key = openedKeys[id] { return .success(key) }
        let found = ruleKeys.lookup(id)
        if case .success(let key) = found { openedKeys[id] = key }
        return found
    }

    /// The key to seal with (F21, G-34): this store's own. The first time, a new key is generated, stored under its id
    /// (never replacing or adopting an item already there), every value readable under an older key is sealed again with
    /// it, and keys no value uses any more are removed from the key store. Later, the key is stored again if another
    /// process removed it meanwhile. Throws `ruleKeyUnavailable` (nothing written) when the key store cannot be asked.
    @discardableResult
    private func prepareSealing() throws -> SymmetricKey {
        if let key = sessionKey {
            let id = RuleSeal.keyID(key)
            do {
                if let stored = try ruleKeys.key(id: id), RuleSeal.keyID(stored) == id { return key }
                try ruleKeys.store(key, id: id)
                return key
            } catch {
                Log.journal.error("rule key unavailable for a write")
                throw JournalError.ruleKeyUnavailable
            }
        }
        let key = SymmetricKey(size: .bits256)
        let id = RuleSeal.keyID(key)
        do { try ruleKeys.store(key, id: id) } catch {
            Log.journal.error("rule key unavailable for a write")
            throw JournalError.ruleKeyUnavailable
        }
        sessionKey = key
        openedKeys[id] = key
        Log.journal.info("rule key created")
        try resealUnderSessionKey(key)
        retireUnusedKeys()
        return key
    }

    /// Every sealed value (rule values and override patterns) that opens under another key is sealed again with `key`, in
    /// one transaction. A value that does
    /// not open stays as it is (and keeps its key, see `retireUnusedKeys`).
    private func resealUnderSessionKey(_ key: SymmetricKey) throws {
        let id = RuleSeal.keyID(key)
        struct Row { let id: String; let action: RuleAction; let kind: RuleKind; let sealed: Data }
        let rows: [Row] = schemaVersion < Self.sealedRulesVersion ? [] : try db.query("SELECT id, action, kind, sealed_value FROM rules", []) { r in
            guard let action = RuleAction(rawValue: r.string(1)), let kind = RuleKind(rawValue: r.string(2)) else {
                throw JournalError.corruptRecord("rule \(r.string(0))")
            }
            return Row(id: r.string(0), action: action, kind: kind, sealed: r.isNull(3) ? Data() : r.data(3))
        }
        var resealed: [(String, Data)] = []
        for row in rows where (try? RuleSeal.keyID(ofSealed: row.sealed).get()) != id {
            guard case .success(let value) = RuleSeal.open(row.sealed, id: row.id, action: row.action, kind: row.kind, keys: { openingKey($0) }) else {
                continue
            }
            resealed.append((row.id, try RuleSeal.seal(value, id: row.id, action: row.action, kind: row.kind, key: key)))
        }
        var overrides: [(String, Data)] = []
        if schemaVersion >= Self.sealedOverridesVersion {
            let rows = try db.query("SELECT detector_id, sealed_specs FROM detector_overrides", []) { (id: $0.string(0), sealed: $0.isNull(1) ? Data() : $0.data(1)) }
            for row in rows where (try? RuleSeal.keyID(ofSealed: row.sealed).get()) != id {
                guard case .success(let json) = OverrideSeal.open(row.sealed, detectorID: row.id, keys: { openingKey($0) }) else { continue }
                overrides.append((row.id, try OverrideSeal.seal(json, detectorID: row.id, key: key)))
            }
        }
        guard !resealed.isEmpty || !overrides.isEmpty else { return }
        try db.transaction {
            for (ruleID, sealed) in resealed {
                try db.run("UPDATE rules SET sealed_value = ? WHERE id = ?", [.blob(sealed), .text(ruleID)])
            }
            for (detectorID, sealed) in overrides {
                try db.run("UPDATE detector_overrides SET sealed_specs = ? WHERE detector_id = ?", [.blob(sealed), .text(detectorID)])
            }
        }
        Log.journal.info("values sealed again under this launch's key rules=\(resealed.count) overrides=\(overrides.count)")
    }

    /// The key ids the stored sealed values name.
    private func referencedKeyIDs() throws -> Set<Data> {
        var blobs = schemaVersion >= Self.sealedRulesVersion
            ? try db.query("SELECT sealed_value FROM rules WHERE sealed_value IS NOT NULL", []) { $0.data(0) } : []
        if schemaVersion >= Self.sealedOverridesVersion {
            blobs += try db.query("SELECT sealed_specs FROM detector_overrides WHERE sealed_specs IS NOT NULL", []) { $0.data(0) }
        }
        return Set(blobs.compactMap { try? RuleSeal.keyID(ofSealed: $0).get() })
    }

    /// Removes from the key store every key no stored value names and that is not this store's own (best effort; a key
    /// that will not go is tried again at the next launch's first write). Counts only in the log.
    private func retireUnusedKeys() {
        guard let sessionKey, let referenced = try? referencedKeyIDs(), let stored = try? ruleKeys.storedKeyIDs() else { return }
        let keep = referenced.union([RuleSeal.keyID(sessionKey)])
        var removed = 0, failed = 0
        for id in stored where !keep.contains(id) {
            do { try ruleKeys.removeKey(id: id); removed += 1 } catch { failed += 1 }
        }
        for id in stored where !keep.contains(id) { openedKeys.removeValue(forKey: id) }
        if removed + failed > 0 { Log.journal.info("rule keys retired=\(removed) failed=\(failed)") }
    }

    /// Seals the value and stores the rule; re-entering an unreadable rule under its id replaces the unreadable value.
    /// Throws `ruleKeyUnavailable` (nothing written) when the key store cannot be asked.
    public func upsertRule(_ rule: RuleRecord) throws {
        guard try ensureSealed() else { throw JournalError.ruleKeyUnavailable }
        try prepareSealing()
        try writeRule(rule)
    }

    private func writeRule(_ rule: RuleRecord) throws {
        // Only ever this store's own key (F21); `prepareSealing` ran before the caller's transaction.
        guard let key = sessionKey else { throw JournalError.ruleKeyUnavailable }
        let sealed = try RuleSeal.seal(rule.value, id: rule.id, action: rule.action, kind: rule.kind, key: key)
        try db.run("""
            INSERT INTO rules (id, action, kind, sealed_value, token_length, name, enabled, created_at, sort_order) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(id) DO UPDATE SET action = excluded.action, kind = excluded.kind, sealed_value = excluded.sealed_value,
              token_length = excluded.token_length, name = excluded.name, enabled = excluded.enabled, created_at = excluded.created_at,
              sort_order = excluded.sort_order
            """, [.text(rule.id), .text(rule.action.rawValue), .text(rule.kind.rawValue), .blob(sealed), SQLValue(rule.tokenLength),
                  SQLValue(rule.name), SQLValue(rule.enabled), .text(ISO.string(rule.createdAt)),
                  .integer(Int64(RuleOrder.clamped(rule.sortOrder)))])   // F16: no stored order can make `+ 1` trap
    }

    public func deleteRule(_ id: String) throws {
        try db.run("DELETE FROM rules WHERE id = ?", [.text(id)])
        if db.changes == 0 { throw JournalError.ruleNotFound(id) }
    }

    public func reorderRules(_ ids: [String]) throws {
        // Ids only: reordering never needs a value, so it works for unreadable rules and without the key.
        let existing = try db.query("SELECT id FROM rules ORDER BY sort_order, created_at", []) { $0.string(0) }
        let known = Set(existing)
        for id in ids where !known.contains(id) { throw JournalError.ruleNotFound(id) }
        let listed = Set(ids)
        let ordered = ids + existing.filter { !listed.contains($0) }
        try db.transaction {
            for (index, id) in ordered.enumerated() {
                try db.run("UPDATE rules SET sort_order = ? WHERE id = ?", [.integer(Int64(index)), .text(id)])
            }
        }
    }

