        _ = try? ensureSealed()
        guard hasSpots else { return [] }
        return try withSpots(db.query("SELECT \(rowColumns) FROM unchecked WHERE settled_at IS NOT NULL ORDER BY settled_at DESC, file_path", [],
                                      unchecked(from:)))
    }

    /// G-40: one row by id, listed or settled, with its spots. Throws `uncheckedNotFound` when there is none.
    public func uncheckedFile(_ id: UUID) throws -> UncheckedRecord {
        _ = try? ensureSealed()
        guard let record = try db.first("SELECT \(rowColumns) FROM unchecked WHERE id = ?", [.text(id.uuidString)], unchecked(from:)) else {
            throw JournalError.uncheckedNotFound(id)
        }
        return try withSpots([record])[0]
    }

    /// G-40: the spot rows with a spot in `entryID` (the picture is in that entry), with their spots.
    public func spotFiles(entryID: UUID) throws -> [UncheckedRecord] {
        _ = try? ensureSealed()
        guard hasSpots else { return [] }
        return try withSpots(db.query("""
            SELECT \(rowColumns) FROM unchecked WHERE id IN (SELECT unchecked_id FROM unread_spots WHERE entry_id = ?)
            ORDER BY last_seen DESC, file_path
            """, [.text(entryID.uuidString)], unchecked(from:)))
    }

    /// G-40: sets the row's spots (their states, entries and covers; the rects stay as the engine found them) and settles
    /// the row when none is pending, or lists it again when one is. Returns the row as it now is. Throws
    /// `uncheckedNotFound` when there is no such row, `corruptRecord` when `spots` does not match its spots in number.
    public func updateSpots(_ id: UUID, spots: [SpotRecord]) throws -> UncheckedRecord {
        let current = try uncheckedFile(id)
        guard hasSpots, current.reason == .unreadPatch, current.spots.count == spots.count, !spots.isEmpty else {
            throw JournalError.corruptRecord("unchecked \(id.uuidString) spots")
        }
        let merged = zip(current.spots, spots).map { old, new in
            SpotRecord(rect: old.rect, coverRect: old.coverRect, state: new.state, entryID: new.entryID, findingID: new.findingID)
        }
        let settled: String? = merged.allSatisfy(\.state.isSettled) ? ISO.string(clock.now()) : nil
        try db.transaction {
            try db.run("UPDATE unchecked SET settled_at = ? WHERE id = ?", [SQLValue(settled), .text(id.uuidString)])
            try writeSpots(merged, uncheckedID: id.uuidString)
        }
        let states = merged.map(\.state.rawValue).joined(separator: ",")
        Log.journal.info("unchecked spots updated states=\(states, privacy: .public) settled=\(settled != nil)")
        return try uncheckedFile(id)
    }

    /// G-40: settled spot rows settled before `cutoff` go, with the Journal's retention.
    private func pruneSettledSpots(before cutoff: Date) throws {
        guard hasSpots else { return }
        try db.run("DELETE FROM unchecked WHERE settled_at IS NOT NULL AND settled_at < ?", [.text(ISO.string(cutoff))])
    }

    private func uncheckedRecord(path: String) throws -> UncheckedRecord {
        guard let record = try db.first("SELECT \(rowColumns) FROM unchecked WHERE file_path = ?", [.text(path)], unchecked(from:)) else {
            throw JournalError.corruptRecord("unchecked row vanished after upsert")
        }
        return try withSpots([record])[0]
    }

    private func writeSpots(_ spots: [SpotRecord], uncheckedID: String) throws {
        try db.run("DELETE FROM unread_spots WHERE unchecked_id = ?", [.text(uncheckedID)])
        for (ordinal, spot) in spots.enumerated() {
            try db.run("""
                INSERT INTO unread_spots (unchecked_id, ordinal, rect_x, rect_y, rect_w, rect_h, cover_x, cover_y, cover_w, cover_h, state,
                                          entry_id, finding_id)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, [.text(uncheckedID), .integer(Int64(ordinal)),
                      .real(Double(spot.rect.minX)), .real(Double(spot.rect.minY)), .real(Double(spot.rect.width)), .real(Double(spot.rect.height)),
                      .real(Double(spot.coverRect.minX)), .real(Double(spot.coverRect.minY)), .real(Double(spot.coverRect.width)),
                      .real(Double(spot.coverRect.height)), .text(spot.state.rawValue), SQLValue(spot.entryID?.uuidString),
                      SQLValue(spot.findingID?.uuidString)])
        }
    }

    /// The rows with their spots read in.
    private func withSpots(_ records: [UncheckedRecord]) throws -> [UncheckedRecord] {
        guard hasSpots else { return records }
        return try records.map { record in
            guard record.reason == .unreadPatch else { return record }
            let spots = try db.query("""
                SELECT rect_x, rect_y, rect_w, rect_h, cover_x, cover_y, cover_w, cover_h, state, entry_id, finding_id
                FROM unread_spots WHERE unchecked_id = ? ORDER BY ordinal
                """, [.text(record.id.uuidString)]) { r -> SpotRecord in
                guard let state = SpotState(rawValue: r.string(8)) else { throw JournalError.corruptRecord("spot state \(record.id.uuidString)") }
                return SpotRecord(rect: CGRect(x: r.double(0), y: r.double(1), width: r.double(2), height: r.double(3)),
                                  coverRect: CGRect(x: r.double(4), y: r.double(5), width: r.double(6), height: r.double(7)),
                                  state: state, entryID: r.optionalString(9).flatMap(UUID.init(uuidString:)),
                                  findingID: r.optionalString(10).flatMap(UUID.init(uuidString:)))
            }
            return UncheckedRecord(id: record.id, filePath: record.filePath, origin: record.origin, reason: record.reason,
                                   firstSeen: record.firstSeen, lastSeen: record.lastSeen, attempts: record.attempts, spots: spots,
                                   settledAt: record.settledAt)
        }
    }

    /// A row as stored; from schema 10 with when its spots were settled (its spots are read in by `withSpots`).
    private func unchecked(from r: SQLiteConnection.Row) throws -> UncheckedRecord {
        let record = try Self.unchecked(from: r)
        guard hasSpots, let settled = r.optionalString(8) else { return record }
        return UncheckedRecord(id: record.id, filePath: record.filePath, origin: record.origin, reason: record.reason, firstSeen: record.firstSeen,
                               lastSeen: record.lastSeen, attempts: record.attempts, settledAt: try ISO.date(settled))
    }

    private static func columns(for origin: UncheckedOrigin) -> (String, String?) {
        switch origin {
        case .screenshotFolder: return ("screenshotFolder", nil)
        case .downloads: return ("downloads", nil)
        case .watched(let folder): return ("watched", folder)
        case .imported: return ("imported", nil)
        }
    }

    private static func unchecked(from r: SQLiteConnection.Row) throws -> UncheckedRecord {
        guard let id = UUID(uuidString: r.string(0)), let reason = UncheckedReason(rawValue: r.string(4)) else {
            throw JournalError.corruptRecord("unchecked \(r.string(0))")
        }
        let origin: UncheckedOrigin
        switch (r.string(2), r.optionalString(3)) {
        case ("screenshotFolder", nil): origin = .screenshotFolder
        case ("downloads", nil): origin = .downloads
        case ("watched", let folder?): origin = .watched(folder: folder)
        case ("imported", nil): origin = .imported
        default: throw JournalError.corruptRecord("unchecked origin \(r.string(0))")
        }
        return UncheckedRecord(id: id, filePath: r.string(1), origin: origin, reason: reason, firstSeen: try ISO.date(r.string(5)),
                               lastSeen: try ISO.date(r.string(6)), attempts: r.int(7))
    }

    // MARK: - Not covered on disk (fail-open #7)

    private static let uncoveredColumns = "id, file_path, source_path, entry_id, first_seen, last_seen, attempts"

    public func recordUncovered(path: String, sourcePath: String, entryID: UUID?) throws -> UncoveredRecord {
        let now = ISO.string(clock.now())
        try db.run("""
            INSERT INTO uncovered_files (\(Self.uncoveredColumns)) VALUES (?, ?, ?, ?, ?, ?, 1)
            ON CONFLICT(file_path) DO UPDATE SET source_path = excluded.source_path, entry_id = excluded.entry_id,
              last_seen = excluded.last_seen, attempts = uncovered_files.attempts + 1
            """, [.text(UUID().uuidString), .text(path), .text(sourcePath), SQLValue(entryID?.uuidString), .text(now), .text(now)])
        guard let record = try db.first("SELECT \(Self.uncoveredColumns) FROM uncovered_files WHERE file_path = ?", [.text(path)],
                                        Self.uncovered(from:)) else {
            throw JournalError.corruptRecord("uncovered row vanished after upsert")
        }
        Log.journal.info("not covered on disk recorded attempts=\(record.attempts)")
        return record
    }

    @discardableResult
    public func clearUncovered(path: String) throws -> [UncoveredRecord] {
        try removeUncovered(where: "file_path = ? OR source_path = ?", [.text(path), .text(path)])
    }

    @discardableResult
    public func clearUncovered(entryID: UUID) throws -> [UncoveredRecord] {
        try removeUncovered(where: "entry_id = ?", [.text(entryID.uuidString)])
    }

    private func removeUncovered(where filter: String, _ binds: [SQLValue]) throws -> [UncoveredRecord] {
        var removed: [UncoveredRecord] = []
        try db.transaction {
            removed = try db.query("SELECT \(Self.uncoveredColumns) FROM uncovered_files WHERE \(filter)", binds, Self.uncovered(from:))
            try db.run("DELETE FROM uncovered_files WHERE \(filter)", binds)
        }
        if !removed.isEmpty { Log.journal.info("not covered on disk cleared count=\(removed.count)") }
        return removed
    }

    public func dismissUncovered(_ id: UUID) throws {
        try db.run("DELETE FROM uncovered_files WHERE id = ?", [.text(id.uuidString)])
        if db.changes == 0 { throw JournalError.uncoveredNotFound(id) }
    }

    public func restoreUncovered(_ record: UncoveredRecord) throws {
        try db.transaction {
            try db.run("DELETE FROM uncovered_files WHERE file_path = ? OR id = ?", [.text(record.filePath), .text(record.id.uuidString)])
            try db.run("INSERT INTO uncovered_files (\(Self.uncoveredColumns)) VALUES (?, ?, ?, ?, ?, ?, ?)",
                       [.text(record.id.uuidString), .text(record.filePath), .text(record.sourcePath), SQLValue(record.entryID?.uuidString),
                        .text(ISO.string(record.firstSeen)), .text(ISO.string(record.lastSeen)), .integer(Int64(max(1, record.attempts)))])
        }
    }

    public func uncoveredFiles() throws -> [UncoveredRecord] {
        try db.query("SELECT \(Self.uncoveredColumns) FROM uncovered_files ORDER BY last_seen DESC, file_path", [], Self.uncovered(from:))
    }

    private static func uncovered(from r: SQLiteConnection.Row) throws -> UncoveredRecord {
        guard let id = UUID(uuidString: r.string(0)) else { throw JournalError.corruptRecord("uncovered \(r.string(0))") }
        let entryID: UUID?
        if let raw = r.optionalString(3) {
            guard let parsed = UUID(uuidString: raw) else { throw JournalError.corruptRecord("uncovered entry \(r.string(0))") }
            entryID = parsed
        } else {
            entryID = nil
        }
        return UncoveredRecord(id: id, filePath: r.string(1), sourcePath: r.string(2), entryID: entryID,
                               firstSeen: try ISO.date(r.string(4)), lastSeen: try ISO.date(r.string(5)), attempts: r.int(6))
    }

