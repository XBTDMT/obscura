    // MARK: - Not checked (G-13)

    private static let uncheckedColumns = "id, file_path, origin, watched_folder, reason, first_seen, last_seen, attempts"
    /// From schema 10 (G-40) a row also says when its spots were all settled.
    private var rowColumns: String { hasSpots ? Self.uncheckedColumns + ", settled_at" : Self.uncheckedColumns }
    /// The file is at schema 10 (G-40): `unchecked.settled_at` and `unread_spots` exist. Below it (a migration waiting
    /// for the key store or for its backup) a spot row is stored as `ocrFailed` with no spots: still listed, never clean.
    private var hasSpots: Bool { schemaVersion >= Self.unreadSpotsVersion }

    public func recordUnchecked(path: String, origin: UncheckedOrigin, reason: UncheckedReason) throws -> UncheckedRecord {
        try recordUnchecked(path: path, origin: origin, reason: reason, spots: [])
    }

    /// G-40: as `recordUnchecked(path:origin:reason:)`, with the spots of an `unreadPatch` row (replacing any it had). The
    /// row is settled (no longer listed, kept as the record) when it has spots and none is pending; any other reason
    /// keeps no spots and is listed.
    public func recordUnchecked(path: String, origin: UncheckedOrigin, reason: UncheckedReason, spots: [SpotRecord]) throws -> UncheckedRecord {
        _ = try? ensureSealed()
        let now = clock.now()
        let (kind, folder) = Self.columns(for: origin)
        guard hasSpots else {
            let stored: UncheckedReason = reason == .unreadPatch ? .ocrFailed : reason
            try db.run("""
                INSERT INTO unchecked (\(Self.uncheckedColumns)) VALUES (?, ?, ?, ?, ?, ?, ?, 1)
                ON CONFLICT(file_path) DO UPDATE SET origin = excluded.origin, watched_folder = excluded.watched_folder,
                  reason = excluded.reason, last_seen = excluded.last_seen, attempts = unchecked.attempts + 1
                """, [.text(UUID().uuidString), .text(path), .text(kind), SQLValue(folder), .text(stored.rawValue), .text(ISO.string(now)),
                      .text(ISO.string(now))])
            return try uncheckedRecord(path: path)
        }
        let kept = reason == .unreadPatch ? spots : []
        let settled: String? = !kept.isEmpty && kept.allSatisfy(\.state.isSettled) ? ISO.string(now) : nil
        let record = try db.transaction { () throws -> UncheckedRecord in
            try db.run("""
                INSERT INTO unchecked (\(Self.uncheckedColumns), settled_at) VALUES (?, ?, ?, ?, ?, ?, ?, 1, ?)
                ON CONFLICT(file_path) DO UPDATE SET origin = excluded.origin, watched_folder = excluded.watched_folder,
                  reason = excluded.reason, last_seen = excluded.last_seen, attempts = unchecked.attempts + 1,
                  settled_at = excluded.settled_at
                """, [.text(UUID().uuidString), .text(path), .text(kind), SQLValue(folder), .text(reason.rawValue), .text(ISO.string(now)),
                      .text(ISO.string(now)), SQLValue(settled)])
            guard let id = try db.first("SELECT id FROM unchecked WHERE file_path = ?", [.text(path)], { $0.string(0) }) else {
                throw JournalError.corruptRecord("unchecked row vanished after upsert")
            }
            try writeSpots(kept, uncheckedID: id)
            return try uncheckedRecord(path: path)
        }
        Log.journal.info("unchecked recorded attempts=\(record.attempts) reason=\(record.reason.rawValue, privacy: .public) spots=\(kept.count) settled=\(settled != nil)")
        return record
    }

    public func clearUnchecked(path: String) throws {
        try db.run("DELETE FROM unchecked WHERE file_path = ?", [.text(path)])
    }

    public func dismissUnchecked(_ id: UUID) throws {
        try db.run("DELETE FROM unchecked WHERE id = ?", [.text(id.uuidString)])
        if db.changes == 0 { throw JournalError.uncheckedNotFound(id) }
    }

    public func restoreUnchecked(_ record: UncheckedRecord) throws {
        _ = try? ensureSealed()
        let (kind, folder) = Self.columns(for: record.origin)
        let reason: UncheckedReason = !hasSpots && record.reason == .unreadPatch ? .ocrFailed : record.reason
        try db.transaction {
            try db.run("DELETE FROM unchecked WHERE file_path = ? OR id = ?", [.text(record.filePath), .text(record.id.uuidString)])
            var values: [SQLValue] = [.text(record.id.uuidString), .text(record.filePath), .text(kind), SQLValue(folder), .text(reason.rawValue),
                                      .text(ISO.string(record.firstSeen)), .text(ISO.string(record.lastSeen)), .integer(Int64(max(1, record.attempts)))]
            if hasSpots {
                let spots = reason == .unreadPatch ? record.spots : []
                let settled = !spots.isEmpty && spots.allSatisfy(\.state.isSettled) ? (record.settledAt ?? clock.now()) : nil
                values.append(SQLValue(settled.map { ISO.string($0) }))
                try db.run("INSERT INTO unchecked (\(Self.uncheckedColumns), settled_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)", values)
                try writeSpots(spots, uncheckedID: record.id.uuidString)
            } else {
                try db.run("INSERT INTO unchecked (\(Self.uncheckedColumns)) VALUES (?, ?, ?, ?, ?, ?, ?, ?)", values)
            }
        }
    }

