/// ISO-8601 UTC with fractional seconds; lexicographic order equals chronological order, which the SQL comparisons rely on.
enum ISO {
    private static let fractional = Date.ISO8601FormatStyle(includingFractionalSeconds: true)
    private static let plain = Date.ISO8601FormatStyle()
    /// Rounds to the millisecond the format keeps before formatting. The format truncates, and a date parsed from
    /// "…​.913Z" is the Double just below .913, so without this a stored date read back and written again lost 1 ms
    /// (about half of all values): a restored row would not be the row it was.
    static func string(_ date: Date) -> String {
        let ms = (date.timeIntervalSinceReferenceDate * 1000).rounded()
        return fractional.format(Date(timeIntervalSinceReferenceDate: ms / 1000 + 0.000_000_1))
    }
    static func date(_ string: String) throws -> Date {
        if let d = try? fractional.parse(string) { return d }
        if let d = try? plain.parse(string) { return d }
        throw JournalError.corruptRecord("date \(string)")
    }
}

/// "YYYY-MM-DD" in the user's calendar and time zone, the key of `stats_days`.
enum LocalDay {
    static var calendar: Calendar { .current }
    static func key(_ date: Date) -> String {
        let c = calendar.dateComponents([.year, .month, .day], from: date)
        return String(format: "%04d-%02d-%02d", c.year ?? 0, c.month ?? 0, c.day ?? 0)
    }
}

enum JSON {
    static func string(_ counts: [String: Int]) throws -> String {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        return String(decoding: try encoder.encode(counts), as: UTF8.self)
    }
    static func strings(_ list: [String]) throws -> String { String(decoding: try JSONEncoder().encode(list), as: UTF8.self) }
    static func stringList(_ json: String) throws -> [String] {
        do { return try JSONDecoder().decode([String].self, from: Data(json.utf8)) } catch { throw JournalError.corruptRecord("string list json") }
    }
    static func counts(_ json: String) throws -> [String: Int] {
        do { return try JSONDecoder().decode([String: Int].self, from: Data(json.utf8)) } catch { throw JournalError.corruptRecord("counts json") }
    }
}

extension Duration {
    var seconds: TimeInterval {
        let c = components
        return TimeInterval(c.seconds) + TimeInterval(c.attoseconds) / 1e18
    }
}
